"use strict";
const { test } = require("node:test"), assert = require("node:assert/strict"), fs = require("node:fs"), path = require("node:path"), os = require("node:os");
const CHROMIUM = process.env.KAI_TEST_CHROMIUM || "/opt/pw-browsers/chromium";

test("credit sign-in and website Connections keep separate views through slow responses and sign-out", { skip: !fs.existsSync(CHROMIUM), timeout: 60000 }, async t => {
  const dataDir = fs.mkdtempSync(path.join(os.tmpdir(), "kai-credit-account-ui-"));
  const core = await require("../server").createCore({ dataDir, port: 0, creditAccountOrigin: "https://credits.koinosai.com", onEvent() {} });
  core.settings.set("network.privacyMode", "local-first");
  let signedIn = false, polls = 0, creditLogouts = 0, websiteLogouts = 0;
  const old = { site: "https://koinosai.com", signedIn: true, thisWalletLinked: true, account: { id: "old-account", email: "website@example.test", wallets: [] } };
  core.account.status = async () => old;
  core.creditAccount.status = async () => ({ site: "https://credits.koinosai.com", signedIn, account: { id: "credit-account", email: "credits@example.test", wallets: [] } });
  core.creditAccount.linkStart = async () => ({ userCode: "CREDIT-CODE", verifyUrl: "https://credits.koinosai.com/link" });
  core.creditAccount.linkPoll = async () => { polls++; signedIn = true; return { pending: false }; };
  core.creditAccount.signOut = async () => { creditLogouts++; signedIn = false; };
  core.account.signOut = async () => { websiteLogouts++; };
  let browser;
  t.after(async () => { await browser?.close(); await core.stop(); fs.rmSync(dataDir, { recursive: true, force: true }); });
  const base = `http://127.0.0.1:${await core.start()}`;
  browser = await require("playwright-core").chromium.launch({ executablePath: CHROMIUM, args: ["--no-sandbox"] });
  const page = await browser.newPage(), errors = []; page.on("pageerror", e => errors.push(e.message));
  await page.addInitScript(() => localStorage.setItem("kai-interface-language", "en"));
  await page.goto(base);
  await page.evaluate(() => window.activateView("settings"));
  await page.waitForFunction(() => document.getElementById("account-heading").textContent === "AI credit account");
  await page.locator("#btn-account-signin").click();
  await page.waitForFunction(() => document.getElementById("account-code").textContent === "CREDIT-CODE");
  assert.equal(await page.locator("#account-verify-link").getAttribute("href"), "https://credits.koinosai.com/link");
  await page.waitForFunction(() => document.getElementById("account-stats").textContent.includes("credits@example.test"));
  assert.equal(polls, 1); assert.equal(await page.locator("#account-web").isVisible(), false);
  await page.locator("#btn-account-scope").click();
  await page.waitForFunction(() => document.getElementById("account-stats").textContent.includes("website@example.test"));
  assert.equal(await page.locator("#account-web").isVisible(), true);
  await Promise.all([page.waitForResponse(r => r.url() === base + "/core/website-account/logout"), page.locator("#btn-account-signout").click()]);
  assert.equal(websiteLogouts, 1); assert.equal(creditLogouts, 0);
  // A response to the previous account tab must not replace the current view.
  let release, entered;
  const pending = new Promise(resolve => { entered = resolve; });
  core.account.status = async () => { entered(); await new Promise(resolve => { release = resolve; }); return old; };
  await page.evaluate(() => { void window.renderAccount(true); }); await pending;
  await page.locator("#btn-account-scope").click();
  await page.waitForFunction(() => document.getElementById("account-heading").textContent === "AI credit account");
  const oldResponse = page.waitForResponse(r => r.url() === base + "/core/website-account");
  release(); await oldResponse;
  await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
  await page.waitForFunction(() => document.getElementById("account-stats").textContent.includes("credits@example.test"));
  await page.locator("#btn-account-signout").click();
  await page.locator("#account-signedout").waitFor({ state: "visible" });
  assert.equal(creditLogouts, 1); assert.equal(websiteLogouts, 1);
  assert.equal(await page.locator("#account-web").isVisible(), false);
  assert.deepEqual(errors, []);
});
